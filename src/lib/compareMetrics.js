/*
  compareMetrics.js — the metric registry for the Company Comparison builder
  (Atlas Section 08).

  Pickers are driven by DATA, not by this file's wishes: coverage() counts,
  for any ticker set, how many companies actually have a figure for a metric.
  A metric with zero coverage never appears in the picker. Nothing here
  invents a figure — every value is resolved live from kpis.json (12
  companies) or comparison.json (NVDA/AMD-only verified extras).

  Explanation layers: `explain` carries the three company-agnostic layers
  (what / why / good). The fourth layer ("what this result means") is
  generated by describeGap() from the live selection — deterministic,
  banned-vocabulary-free.

  Banned vocabulary (never in any string below): buy, sell, undervalued,
  overvalued, cheap, expensive, should, recommend, target, poised, set to.
*/
