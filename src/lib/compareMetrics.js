/* ------------------------------------------------------------------ */
/* Resolution — figures come from the datasets, never from this file    */
/* ------------------------------------------------------------------ */

function figureFromKpis(ticker, label) {
  const rec = kpisByTicker[ticker]
  if (!rec) return null
  const m = rec.metrics.find((x) => x.label === label)
  if (!m || m.value == null) return null
  return { value: m.value, sub: m.sub || '', tier: m.tier, source: rec.source, asOf: rec.asOf }
}

function figureFromComparison(ticker, label) {
  for (const fam of comparison.families || []) {
    const m = (fam.metrics || []).find((x) => x.label === label)
    if (!m) continue
    const fig = ticker === 'NVDA' ? m.nvda : ticker === 'AMD' ? m.amd : null
    if (fig && fig.value != null) return { ...fig, reading: m.reading, explain: m.explain, stronger: m.stronger }
  }
  return null
}

/** Resolve one metric for one ticker → figure object or null. */
export function resolveFigure(metricId, ticker) {
  const def = METRICS.find((m) => m.id === metricId)
  if (!def) return null
  for (const s of def.sources) {
    if (s.kind === 'kpis') {
      const label = s.perTicker ? s.perTicker[ticker] : s.label
      if (!label) continue
      const fig = figureFromKpis(ticker, label)
      if (fig) return { ...fig, metricId, ticker }
    } else if (s.kind === 'comparison') {
      const fig = figureFromComparison(ticker, s.label)
      if (fig) return { ...fig, metricId, ticker }
    }
  }
  return null
}

/** How many of the given tickers have data for this metric. */
export function coverage(metricId, tickers) {
  return tickers.filter((t) => resolveFigure(metricId, t) != null).length
}

/** Metrics with ≥1 company holding data — the only ones the picker may show. */
export function availableMetrics(allTickers) {
  return METRICS.filter((m) => coverage(m.id, allTickers) > 0)
}

/* ------------------------------------------------------------------ */
/* Generated 4th explanation layer + takeaways (deterministic)          */
/* ------------------------------------------------------------------ */

function ratioText(vals) {
  const nums = vals.map((v) => parseScalar(v)).filter((n) => n != null && n > 0)
  if (nums.length < 2) return ''
  const mx = Math.max(...nums)
  const mn = Math.min(...nums)
  if (mn <= 0) return ''
  const r = mx / mn
  return r >= 1.5 ? ` — a ${r >= 10 ? Math.round(r) : r.toFixed(1)}× spread` : ''
}

/** "What this result means" generated from the live selection. */
export function describeGap(def, figs) {
  const withVal = figs.filter((f) => f && f.value != null)
  if (withVal.length === 0) return 'No figures available for the selected companies.'
  const scored = withVal
    .map((f) => ({ f, n: parseScalar(f.value) }))
    .filter((s) => s.n != null)
  if (scored.length === 0) {
    return `${withVal.map((s) => `${s.ticker} ${s.value}`).join(' · ')}.`
  }
  const desc = def.higherIsBetter === false
  const sorted = [...scored].sort((a, b) => (desc ? a.n - b.n : b.n - a.n))
  const lead = sorted[0]
  const tail = sorted[sorted.length - 1]
  if (sorted.length === 1) {
    return `${lead.f.ticker} reports ${lead.f.value}. No peer selected for comparison.`
  }
  const spread = ratioText(scored.map((s) => s.f.value))
  return `${lead.f.ticker} leads at ${lead.f.value} vs ${tail.f.ticker} ${tail.f.value}${spread}.`
}

/** Top-3 biggest relative gaps across the selected metrics — hero callouts. */
export function topTakeaways(metricIds, tickers) {
  const scored = []
  for (const id of metricIds) {
    const def = METRICS.find((m) => m.id === id)
    if (!def || def.higherIsBetter == null) continue
    const figs = tickers.map((t) => resolveFigure(id, t)).filter(Boolean)
    const nums = figs.map((f) => ({ f, n: parseScalar(f.value) })).filter((s) => s.n != null && s.n > 0)
    if (nums.length < 2) continue
    const mx = Math.max(...nums.map((s) => s.n))
    const mn = Math.min(...nums.map((s) => s.n))
    if (mn <= 0 || mx / mn < 1.5) continue
    const lead = nums.reduce((a, b) => (def.higherIsBetter === false ? (a.n < b.n ? a : b) : (a.n > b.n ? a : b)))
    scored.push({ def, lead, ratio: mx / mn })
  }
  scored.sort((a, b) => b.ratio - a.ratio)
  return scored.slice(0, 3).map(({ def, lead, ratio }) => ({
    figure: lead.f.value.split(' ')[0],
    sub: `${def.label} — ${lead.f.ticker} leads${ratio >= 10 ? ` by ${Math.round(ratio)}×` : ` (${ratio.toFixed(1)}× spread)`}`,
  }))
}
